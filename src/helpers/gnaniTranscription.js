const fs = require("node:fs");
const path = require("node:path");
const { setTimeout: delay } = require("node:timers/promises");
const { GNANI_STT_URL, resolveGnaniConfig } = require("./gnaniConfig");
const { convertToWav, convertBufferToWav, isPcm16Mono16kWav } = require("./ffmpegUtils");
const { pcm16ToWav } = require("../utils/audioUtils");
const { getSafeTempDir } = require("./safeTempDir");
const { asProviderError, providerError, PROVIDER_ERROR_CODES } = require("./providerHttpErrors");
const {
  assembleChunkTranscript,
  CLOUD_CHUNK_MAX_LOSS_RATIO,
  SILENT_CHUNK,
} = require("./cloudChunkPolicy");

const BYTES_PER_SECOND = 32000;
const REST_CLIP_SECONDS = 30;
const FOUR_HOURS = 4 * 60 * 60;

function pcmRange(header, totalBytes) {
  for (let offset = 12; offset + 8 <= header.length;) {
    const size = header.readUInt32LE(offset + 4);
    const start = offset + 8;
    if (header.toString("ascii", offset, offset + 4) === "data") {
      if (start + size > totalBytes || size % 2) break;
      return { start, size };
    }
    offset = start + size + (size % 2);
  }
  throw new Error("Incomplete PCM audio in the recording.");
}

function createGnaniClient({ apiKey, model, signal, fetchImpl = fetch }) {
  const context = { provider: "GnaniAI", surface: "transcription", model };
  if (!apiKey) throw providerError(PROVIDER_ERROR_CODES.KEY_MISSING, context);
  // Only paths generated by the adapter reach this client. Presigned storage
  // transfers use a separate request without provider credentials.
  return async (
    suffix,
    options = {},
    { retry = false, timeoutMs = 45000, maxWaitMs = 10000 } = {}
  ) => {
    for (let attempt = 0; ; attempt++) {
      signal?.throwIfAborted();
      const timeout = AbortSignal.timeout(timeoutMs);
      const requestSignal = signal ? AbortSignal.any([signal, timeout]) : timeout;
      try {
        const response = await fetchImpl(GNANI_STT_URL + suffix, {
          ...options,
          headers: { ...options.headers, "X-API-Key-ID": apiKey },
          redirect: "error",
          signal: requestSignal,
        });
        const body = await response.json().catch(() => null);
        requestSignal.throwIfAborted();
        if (response.ok) {
          if (!body || typeof body !== "object") throw new Error("GnaniAI returned invalid JSON.");
          return body;
        }
        const failure = Object.assign(new Error("GnaniAI request failed."), {
          statusCode: response.status,
          responseHeaders: response.headers,
          requestId: body?.request_id ?? response.headers.get("x-request-id"),
        });
        const retryAfter = response.headers.get("retry-after");
        if (retryAfter) {
          failure.retryAfterMs = /^\d+(\.\d+)?$/.test(retryAfter)
            ? Number(retryAfter) * 1000
            : Math.max(0, Date.parse(retryAfter) - Date.now());
        }
        throw failure;
      } catch (error) {
        signal?.throwIfAborted();
        const transient =
          timeout.aborted ||
          error instanceof TypeError ||
          [408, 429, 500, 502, 503, 504].includes(error.statusCode);
        const wait = error.retryAfterMs ?? 750;
        if (
          attempt === 0 &&
          (retry === true || (retry === "rate-limit" && error.statusCode === 429)) &&
          transient &&
          wait <= maxWaitMs
        ) {
          await delay(wait, undefined, { signal });
          continue;
        }
        const failure = asProviderError(timeout.aborted ? timeout.reason : error, context);
        if (error.statusCode) failure.statusCode = error.statusCode;
        if (typeof error.requestId === "string" && /^[\w.-]{1,128}$/.test(error.requestId)) {
          failure.technicalDetails = { ...failure.technicalDetails, requestId: error.requestId };
        }
        throw failure;
      }
    }
  };
}

async function transcribeSpan(pcm, config, request) {
  const form = new FormData();
  form.set("audio_file", new Blob([pcm16ToWav(pcm)], { type: "audio/wav" }), "recording.wav");
  form.set("model", config.model);
  form.set("language_code", config.languageCode);
  form.set("format", config.format);
  if (config.keyterms.length) form.set("keyterms", JSON.stringify(config.keyterms));
  const body = await request("", { method: "POST", body: form }, { retry: true });
  if (
    body.success !== true ||
    typeof body.transcript !== "string" ||
    (body.truncated != null && typeof body.truncated !== "boolean") ||
    (body.model && body.model !== config.model)
  ) {
    throw new Error("GnaniAI returned an invalid transcription.");
  }
  return {
    text: body.transcript.trim(),
    truncated: body.truncated === true,
    language:
      body.detected_language_code ||
      (config.languageCode !== "indic-auto" ? config.languageCode : undefined),
    requestId: body.request_id,
  };
}

async function transcribePcm(pcm, config, request, signal) {
  const results = [];
  const chunkBoundaries = [0];
  const chunkBytes = REST_CLIP_SECONDS * BYTES_PER_SECOND;
  let failed = 0;
  let lostBytes = 0;
  let firstError;
  let language;
  async function visit(start, end, depth) {
    signal?.throwIfAborted();
    let part;
    try {
      part = await transcribeSpan(pcm.subarray(start, end), config, request);
      if (part.truncated && (depth >= 2 || end - start < BYTES_PER_SECOND))
        throw new Error(
          "GnaniAI returned an incomplete transcript for this part of the recording."
        );
    } catch (error) {
      signal?.throwIfAborted();
      if (error.statusCode && ![408, 500, 502, 503, 504].includes(error.statusCode)) throw error;
      firstError ??= error;
      failed++;
      lostBytes += end - start;
      results.push(null);
      chunkBoundaries.push(end / BYTES_PER_SECOND);
      return;
    }
    if (part.truncated) {
      const mid = start + 2 * Math.floor((end - start) / 4);
      await visit(start, mid, depth + 1);
      await visit(mid, end, depth + 1);
      return;
    }
    language ||= part.language;
    results.push(part.text ? part : SILENT_CHUNK);
    chunkBoundaries.push(end / BYTES_PER_SECOND);
  }
  for (let offset = 0; offset < pcm.length; offset += chunkBytes) {
    await visit(offset, Math.min(offset + chunkBytes, pcm.length), 0);
  }
  if (lostBytes > pcm.length * CLOUD_CHUNK_MAX_LOSS_RATIO) throw firstError;
  return {
    text: assembleChunkTranscript(results, REST_CLIP_SECONDS, pcm.length / BYTES_PER_SECOND, {
      chunkBoundaries,
    }),
    language,
    ...(failed
      ? { warning: "PARTIAL_TRANSCRIPT", failedChunks: failed, totalChunks: results.length }
      : {}),
  };
}

async function transcribeGnaniRecording({ audioBuffer, ...options }) {
  const config = resolveGnaniConfig(options);
  const request = createGnaniClient({ ...options, model: config.model });
  const buffer = Buffer.from(audioBuffer);
  if (!buffer.length) return { text: "" };
  const wav = isPcm16Mono16kWav(buffer)
    ? buffer
    : await convertBufferToWav(buffer, { signal: options.signal });
  const { start, size } = pcmRange(wav, wav.length);
  return transcribePcm(wav.subarray(start, start + size), config, request, options.signal);
}

async function transcribeGnaniFile({
  filePath,
  diarize = false,
  numSpeakers,
  onProgress,
  ...options
}) {
  const config = resolveGnaniConfig(options);
  const request = createGnaniClient({ ...options, model: config.model });
  const dir = await fs.promises.mkdtemp(path.join(getSafeTempDir(), "ow-gnani-"));
  const wavPath = path.join(dir, "recording.wav");
  try {
    await convertToWav(filePath, wavPath, {
      signal: options.signal,
      maxDurationSeconds: FOUR_HOURS + 1,
    });
    const wav = await fs.openAsBlob(wavPath, { type: "audio/wav" });
    const header = Buffer.from(await wav.slice(0, 65536).arrayBuffer());
    const { start, size } = pcmRange(header, wav.size);
    const durationSeconds = size / BYTES_PER_SECOND;
    if (durationSeconds > FOUR_HOURS)
      throw new Error("GnaniAI accepts recordings up to four hours long.");
    let result;
    if (durationSeconds <= REST_CLIP_SECONDS && !diarize) {
      const pcm = Buffer.from(await wav.slice(start, start + size).arrayBuffer());
      result = await transcribePcm(pcm, config, request, options.signal);
    } else {
      const { transcribeGnaniBatch } = require("./gnaniBatch");
      result = await transcribeGnaniBatch({
        wav,
        config,
        diarize,
        numSpeakers,
        request,
        onProgress,
        ...options,
        // Some deployments route the documented presigned create to a 404.
        // A lossless FLAC can still fit in a single inline file with continuous speaker IDs.
        compactFile: async () => {
          const flacPath = path.join(dir, "recording.flac");
          await require("./ffmpegUtils").convertToFlac(wavPath, flacPath, {
            signal: options.signal,
          });
          return fs.openAsBlob(flacPath, { type: "audio/flac" });
        },
      });
    }
    return { ...result, durationSeconds };
  } finally {
    await fs.promises.rm(dir, { recursive: true, force: true });
  }
}

module.exports = { transcribeGnaniRecording, transcribeGnaniFile, createGnaniClient };
