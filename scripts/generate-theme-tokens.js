function resolve(tokens, name, mode, seen = []) {
  const token = tokens[name];
  if (!token) throw new Error(`Unknown Figma token "${name}" (via ${seen.join(" -> ") || "map"})`);
  const value = token[mode];
  if (value === undefined) throw new Error(`Token "${name}" has no ${mode} value`);
  const alias = /^\{(.+)\}$/.exec(value);
  if (!alias) return value;
  if (seen.includes(name)) throw new Error(`Alias cycle at "${name}"`);
  return resolve(tokens, alias[1], mode, [...seen, name]);
}

function declarations(tokens, mode) {
  return Object.entries(CODE_TOKENS)
    .map(([code, figma]) => `  --color-${code}: ${resolve(tokens, figma, mode)}; /* ${figma} */`)
    .join("\n");
}

const { tokens, source } = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
const css = `/* Generated by scripts/generate-theme-tokens.js from design/tokens/colors.json
   (Figma file ${source.fileKey}, read ${source.readAt}). Do not edit by hand:
   change the Figma variable, update the JSON, and regenerate. */

@theme {
${declarations(tokens, "light")}
}

.dark {
${declarations(tokens, "dark")}
}
`;

fs.writeFileSync(OUTPUT, css);
console.log(
  `Wrote ${path.relative(process.cwd(), OUTPUT)}: ${Object.keys(CODE_TOKENS).length} tokens from ${Object.keys(tokens).length} Figma variables`
);
