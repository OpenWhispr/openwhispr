#!/usr/bin/env node
// Writes src/styles/theme-tokens.css from design/tokens/colors.json (the Figma
// Colors collection). Code uses Figma's names: every variable is
// --color-<group>-<name>, usable on any property (bg-surface-primary,
// bg-text-primary/5). The groups that belong to one property also get a short
// name on it, so text and border utilities do not repeat the group:
// text/primary is text-primary, border/default is border-default, red/text is
// text-red and red/border is border-red.
const fs = require("fs");
const path = require("path");

const SOURCE = path.join(__dirname, "..", "design", "tokens", "colors.json");
const OUTPUT = path.join(__dirname, "..", "src", "styles", "theme-tokens.css");

const cssName = (figmaName) => `--color-${figmaName.replace("/", "-")}`;

// The property-scoped Tailwind namespaces a Figma variable is also reachable from.
function shortNames(figmaName) {
  const [group, name] = figmaName.split("/");
  if (group === "text") return [`--text-color-${name}`];
  if (name === "text") return [`--text-color-${group}`];
  if (figmaName === "border/focus") {
    return ["--border-color-focus", "--ring-color-focus", "--outline-color-focus"];
  }
  if (group === "border") return [`--border-color-${name}`];
  if (name === "border") return [`--border-color-${group}`];
  return [];
}

function resolve(tokens, name, mode, seen = []) {
  const token = tokens[name];
  if (!token) throw new Error(`Unknown Figma token "${name}" (via ${seen.join(" -> ")})`);
  const value = token[mode];
  if (value === undefined) throw new Error(`Token "${name}" has no ${mode} value`);
  const alias = /^\{(.+)\}$/.exec(value);
  if (!alias) return value;
  if (seen.includes(name)) throw new Error(`Alias cycle at "${name}"`);
  return resolve(tokens, alias[1], mode, [...seen, name]);
}

function buildThemeCss({ tokens, source }) {
  const names = Object.keys(tokens);
  const values = (mode) =>
    names.map((name) => `  ${cssName(name)}: ${resolve(tokens, name, mode)};`).join("\n");
  const shortPairs = names.flatMap((name) => shortNames(name).map((short) => [short, name]));
  const taken = new Map();
  for (const [short, name] of shortPairs) {
    if (taken.has(short))
      throw new Error(`"${name}" and "${taken.get(short)}" both shorten to ${short}`);
    taken.set(short, name);
  }
  const shorts = shortPairs.map(([short, name]) => `  ${short}: var(${cssName(name)});`).join("\n");

  return `/* Generated by scripts/generate-theme-tokens.js from design/tokens/colors.json
   (Figma file ${source.fileKey}, read ${source.readAt}). Do not edit by hand:
   change the Figma variable, update the JSON, and regenerate. */

@theme {
${values("light")}
}

/* Short names on the one property a group belongs to. Inline, so a scope that
   overrides a --color-* variable changes these too. */
@theme inline {
${shorts}
}

.dark {
${values("dark")}
}
`;
}

module.exports = { SOURCE, OUTPUT, buildThemeCss, cssName, shortNames };

if (require.main === module) {
  const data = JSON.parse(fs.readFileSync(SOURCE, "utf8"));
  fs.writeFileSync(OUTPUT, buildThemeCss(data));
  console.log(
    `Wrote ${path.relative(process.cwd(), OUTPUT)}: ${Object.keys(data.tokens).length} Figma variables`
  );
}
